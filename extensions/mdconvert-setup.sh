#!/bin/bash
# Rebuild the MarkItDown venv (~/.venvs/markitdown-venv) and the mdconvert CLI
# (~/.local/bin/mdconvert) that extensions/mdconvert.ts wraps.
#
# Both the venv and the CLI live outside this repo, so a fresh OS install loses
# them and the pi mdconvert tool starts failing with exit code 1. Re-run this
# script after a reinstall; it is idempotent.
#
#   bash ~/.pi/agent/extensions/mdconvert-setup.sh
#
# Extras installed: pdf, docx, pptx, xlsx, xls, outlook, youtube-transcription.
# Deliberately skipped: audio-transcription (needs ffmpeg and a speech backend)
# and az-* (Azure cloud document intelligence).

set -euo pipefail

VENV="$HOME/.venvs/markitdown-venv"
CLI_SRC="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/mdconvert-cli.py"
CLI_DST="$HOME/.local/bin/mdconvert"
EXTRAS="pdf,docx,pptx,xlsx,xls,outlook,youtube-transcription"

echo "=== venv: $VENV ==="
python3 -m venv "$VENV"
"$VENV/bin/pip" install --upgrade pip
echo "=== extras: $EXTRAS ==="
"$VENV/bin/pip" install "markitdown[$EXTRAS]"

echo "=== CLI wrapper: $CLI_DST -> $CLI_SRC ==="
chmod +x "$CLI_SRC"
mkdir -p "$(dirname "$CLI_DST")"
# rm first: if the old symlink is still there, cat would write through it and
# clobber mdconvert-cli.py.
rm -f "$CLI_DST"
cat > "$CLI_DST" <<WRAP
#!/bin/sh
# Generated by mdconvert-setup.sh. Runs the CLI with the venv interpreter so the
# shebang in mdconvert-cli.py does not have to hardcode a home directory.
exec "\$HOME/.venvs/markitdown-venv/bin/python" "$CLI_SRC" "\$@"
WRAP
chmod +x "$CLI_DST"

echo "=== smoke test ==="
tmp="$(mktemp -d)"
printf 'name,qty\nbamboo,2\n' > "$tmp/smoke.csv"
"$CLI_DST" "$tmp/smoke.csv"
cat "$tmp/smoke.md"
rm -rf "$tmp"

echo "=== done ==="
